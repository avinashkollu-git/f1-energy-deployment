"""Run everything: validate the model on the real lap, compare strategies, benchmark C++ vs Python.

Writes results/summary.md (numbers quoted in the README) and results/run.npz (traces for plots).
"""
import time
from dataclasses import replace

import numpy as np

from cpp_lapsim import simulate_cpp
from model import CAR_2025, CAR_2026, DS, ROOT, calibrate, load_track, simulate
from strategies import run_all

E0 = 2.0e6  # race lap starts at half of the 4 MJ window
OUT = ROOT / "results"


def main() -> None:
    OUT.mkdir(exist_ok=True)
    lines = ["# Results (generated by `make run`)", ""]
    traces = {}

    # 1. Validation: 2025-spec car, full battery, deploy everywhere (qualifying lap) vs the real lap.
    mu, cda = calibrate()
    lines += ["## Model vs real lap (2025 Monza Q, car #1)", "",
              f"Calibrated: mu = {mu:.2f}, CdA = {cda:.2f} m^2 (defaults in model.Car: "
              f"mu = {CAR_2026.mu:.2f}, CdA = {CAR_2026.cda:.2f})", ""]
    car25 = replace(CAR_2025, mu=mu, cda=cda)
    track = load_track(car25)
    r = simulate(car25, track, np.full(len(track.s), car25.p_k_max), car25.e_window)
    err_kmh = (r["v"] - track.v_real) * 3.6
    lines += ["| metric | value |", "|---|---|",
              f"| real lap time | {track.t_real:.3f} s |",
              f"| model lap time | {r['lap_time']:.3f} s ({r['lap_time'] - track.t_real:+.3f} s) |",
              f"| speed RMSE | {np.sqrt(np.mean(err_kmh ** 2)):.1f} km/h |",
              f"| mean speed error | {err_kmh.mean():+.1f} km/h |",
              f"| worst speed error | {np.abs(err_kmh).max():.0f} km/h |",
              f"| top speed real / model | {track.v_real.max() * 3.6:.0f} / {r['v'].max() * 3.6:.0f} km/h |",
              f"| slowest point real / model | {track.v_real.min() * 3.6:.0f} / {r['v'].min() * 3.6:.0f} km/h |",
              ""]
    traces.update(s=track.s, v_real=track.v_real, v_val=r["v"])

    # 2. Strategies on the 2026-style car, same track.
    track26 = load_track(CAR_2026)
    t0 = time.perf_counter()
    results = run_all(CAR_2026, track26, E0)
    t_strat = time.perf_counter() - t0
    best = results["dynamic programming"][0]["lap_time"]
    lines += [f"## Strategies (2026-style car, start SoC {E0 / 1e6:.1f} MJ of {CAR_2026.e_window / 1e6:.1f} MJ)", "",
              "| strategy | lap time | vs DP | deployed | harvested | end SoC | min SoC | clipping | note |",
              "|---|---|---|---|---|---|---|---|---|"]
    for name, (res, info, _) in results.items():
        lines.append(f"| {name} | {res['lap_time']:.3f} s | {res['lap_time'] - best:+.3f} s | "
                     f"{res['deployed'] / 1e6:.2f} MJ | {res['harvested'] / 1e6:.2f} MJ | "
                     f"{res['e'][-1] / 1e6:.2f} MJ | {res['e'].min() / 1e6:.2f} MJ | {res['clipped_m']:.0f} m | {info} |")
        key = name.split()[0].replace("-", "_")
        traces.update({f"{key}_v": res["v"], f"{key}_e": res["e"], f"{key}_pk": res["p_k"],
                       f"{key}_clip": res["clipped"]})
    lines += ["", f"All three strategies took {t_strat:.1f} s to compute (Python).", ""]

    # 3. C++ vs Python: same answer, how much faster.
    lines += ["## C++ core vs Python", "", "| strategy | Python lap | C++ lap | max speed diff | max SoC diff |",
              "|---|---|---|---|---|"]
    for name, (_, _, cm) in results.items():
        py, cpp = simulate(CAR_2026, track26, cm, E0), simulate_cpp(CAR_2026, track26, cm, E0)
        lines.append(f"| {name} | {py['lap_time']:.6f} s | {cpp['lap_time']:.6f} s | "
                     f"{np.abs(py['v'] - cpp['v']).max():.1e} m/s | {np.abs(py['e'] - cpp['e']).max():.1e} J |")
    cmd = results["dynamic programming"][2]
    n_py, n_cpp = 20, 2000
    t0 = time.perf_counter()
    for _ in range(n_py):
        simulate(CAR_2026, track26, cmd, E0)
    t_py = (time.perf_counter() - t0) / n_py
    t0 = time.perf_counter()
    for _ in range(n_cpp):
        simulate_cpp(CAR_2026, track26, cmd, E0)
    t_cpp = (time.perf_counter() - t0) / n_cpp
    lines += ["", f"One lap ({len(track26.s)} steps of {DS:.0f} m): Python {t_py * 1e3:.2f} ms, "
              f"C++ {t_cpp * 1e6:.1f} us (incl. ctypes call) -> **{t_py / t_cpp:.0f}x faster**", ""]

    (OUT / "summary.md").write_text("\n".join(lines))
    np.savez(OUT / "run.npz", **traces)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
